test('expired browser cookie produces a real 401 and clears frontend identity', async ({ page, context }) => {
  const email = await registerAccount(page)
  await loginAccount(page, email)
  const cookie = (await context.cookies()).find((item) => item.name === 'weibiye_session')!
  await context.addCookies([{ ...cookie, expires: Math.floor(Date.now() / 1000) - 10 }])
  await page.getByLabel('账户头像，打开账户菜单', { exact: true }).click()
  await page.getByRole('navigation', { name: '账户选项', exact: true }).getByRole('link', { name: '登录会话', exact: true }).click()
  await expect(page).toHaveURL(/\/login/)
  await expect(page.getByRole('status')).toContainText('登录已过期')
})

test('authenticated cookies alone cannot bypass CSRF', async ({ page, context }) => {
  const email = await registerAccount(page)
  await loginAccount(page, email)
  expect((await context.request.post('/api/v1/auth/logout', { headers: { Origin: new URL(page.url()).origin } })).status()).toBe(403)
  expect((await context.request.get('/api/v1/auth/me')).status()).toBe(200)
})

test('switching real accounts clears previous local chats and topic consent', async ({ page }) => {
  const mock = await installP3ChatMock(page)
  const email = await registerAccount(page, '账户 A')
  await loginAccount(page, email)
  await mock.seed('账户 A 的已保存会话')
  await page.goto('/preferences/conversations')
  await page.getByRole('checkbox', { name: '允许当前账户历史话题推荐' }).check()
  await expect(page.getByText('正在保存授权设置…', { exact: true })).toHaveCount(0)
  await page.getByRole('link', { name: '返回聊天首页', exact: true }).click()
  await expect(page.getByRole('region', { name: '最近话题', exact: true })).toBeVisible()
  await page.goto('/me')
  await page.getByRole('button', { name: '退出登录', exact: true }).click()
  await expect(page).toHaveURL(/\/login/)
  const second = await registerAccount(page, '账户 B')
  await loginAccount(page, second)
  await expect(page.getByRole('region', { name: '最近话题', exact: true })).toHaveCount(0)
  await expect(page.getByRole('navigation', { name: '历史会话' }).getByRole('link')).toHaveCount(0)
})

test('mobile registration and login preserve the responsive chat homepage', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/register')
  await page.screenshot({ path: '.verification/auth/register-mobile.png', fullPage: true })
  const email = await registerAccount(page, '手机同学')
  await loginAccount(page, email)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await expect(page.getByPlaceholder('愿意和我聊聊吗？', { exact: true })).toBeVisible()
  await page.goto('/me')
  await expect(page.getByRole('heading', { level: 1 })).toContainText('个人中心')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: '.verification/auth/profile-mobile.png', fullPage: true })
  await page.goto('/')
  // A full navigation restores the Cookie session asynchronously. Opening the
  // drawer before that completes would target the temporary visitor scope,
  // which must be discarded when the authenticated scope is mounted.
  await expect(page.getByLabel('账户头像，打开账户菜单', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '打开导航', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '导航菜单' })).toBeVisible()
  await page.screenshot({ path: '.verification/auth/chat-mobile.png', fullPage: true })
})

test('logout in another tab clears previous chats before another account is restored', async ({ page, context }) => {
  const mock = await installP3ChatMock(page)
  const first = await registerAccount(page, '标签页账户 A')
  await loginAccount(page, first)
  await mock.seed('标签页账户 A 的已保存会话')
  await page.goto('/preferences/conversations')
  await page.getByRole('checkbox', { name: '允许当前账户历史话题推荐' }).check()
  await expect(page.getByText('正在保存授权设置…', { exact: true })).toHaveCount(0)
  await page.getByRole('link', { name: '返回聊天首页', exact: true }).click()
  const secondTab = await context.newPage()
  await secondTab.goto('/me')
  await secondTab.getByRole('button', { name: '退出登录', exact: true }).click()
  await expect(page.getByLabel('访客头像，打开账户菜单', { exact: true })).toBeVisible()
  await expect(page.getByRole('region', { name: '最近话题', exact: true })).toHaveCount(0)
  const second = await registerAccount(secondTab, '标签页账户 B')
  await loginAccount(secondTab, second)
  await page.getByLabel('账户头像，打开账户菜单', { exact: true }).click()
  await expect(page.getByRole('navigation', { name: '账户选项', exact: true })).toContainText(second)
  await expect(page.getByRole('navigation', { name: '历史会话' }).getByRole('link')).toHaveCount(0)
  await secondTab.close()
})
