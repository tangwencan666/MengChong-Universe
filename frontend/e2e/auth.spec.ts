import { mkdir } from 'node:fs/promises'
import { test, expect } from '@playwright/test'
import { browserPassword, loginAccount, registerAccount } from './helpers/auth'
import { disposeP3ChatMock, installP3ChatMock } from './helpers/p3-chat-mock'

test.afterEach(async ({ page }) => { await disposeP3ChatMock(page) })

test('desktop registration, login, reload and logout use a real server session', async ({ page, context }) => {
  const email = await registerAccount(page)
  await loginAccount(page, email)
  await expect(page.getByPlaceholder('愿意和我聊聊吗？', { exact: true })).toBeVisible()
  const cookies = await context.cookies()
  const session = cookies.find((cookie) => cookie.name === 'weibiye_session')
  expect(session?.httpOnly).toBe(true)
  expect(session?.sameSite).toBe('Lax')
  expect(await page.evaluate(() => ({ local: localStorage.length, session: sessionStorage.length }))).toEqual({ local: 0, session: 0 })
  await page.goto('/me')
  await expect(page.getByText(email, { exact: true }).last()).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { level: 1 })).toContainText('个人中心')
  await mkdir('.verification/auth', { recursive: true })
  await page.screenshot({ path: '.verification/auth/profile-desktop.png', fullPage: true })
  await page.getByRole('button', { name: '退出登录', exact: true }).click()
  await expect(page).toHaveURL(/\/login/)
  expect((await context.request.get('/api/v1/auth/me')).status()).toBe(401)
})

test('duplicate registration is generic and wrong credentials never create identity', async ({ page }) => {
  const email = await registerAccount(page)
  await page.goto('/register')
  await page.getByLabel('昵称', { exact: true }).fill('重复注册')
  await page.getByLabel('邮箱', { exact: true }).fill(email)
  await page.getByLabel('密码', { exact: true }).fill(browserPassword)
  await page.getByRole('button', { name: '注册', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  await expect(page.getByRole('status')).not.toContainText('已存在')
  await page.getByLabel('邮箱', { exact: true }).fill(email)
  await page.getByLabel('密码', { exact: true }).fill('Wrong-Password!2026')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('邮箱或密码不正确')
})

test('private routes require login and return to the requested page', async ({ page }) => {
  const email = await registerAccount(page)
  await page.goto('/memory')
  await expect(page).toHaveURL(/\/login\?next=/)
  await page.getByLabel('邮箱', { exact: true }).fill(email)
  await page.getByLabel('密码', { exact: true }).fill(browserPassword)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/\/memory$/)
  await expect(page.getByRole('heading', { level: 1 })).toContainText('记忆管理')
  await page.goto('/admin')
  await expect(page.getByRole('heading', { name: '没有访问权限', exact: true })).toBeVisible()
  await page.goto('/login?next=%2FLOGIN%2F')
  await expect(page).toHaveURL(/\/$/)
})

