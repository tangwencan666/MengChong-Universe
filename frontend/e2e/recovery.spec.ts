import { mkdir } from 'node:fs/promises'
import { expect, test } from '@playwright/test'
import { browserPassword, loginAccount, registerAccount } from './helpers/auth'
import { waitForMail } from './helpers/mail'

const recoveredPassword = 'Browser-Recovered-Safe!2026'

test('email link verifies the address, is removed from history, and is single use', async ({ page, context }) => {
  const email = await registerAccount(page)
  const mail = await waitForMail(email, 'verification')
  await page.goto(mail.link!)
  await expect(page).toHaveURL(/\/verify-email$/)
  await expect(page.getByLabel('验证令牌', { exact: true })).not.toHaveValue('')
  await page.getByRole('button', { name: '确认验证邮箱', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('邮箱验证成功')
  expect((await context.request.get('/api/v1/auth/me')).status()).toBe(401)
  await loginAccount(page, email)
  await page.goto('/me')
  await expect(page.getByText('邮箱：已验证', { exact: true })).toBeVisible()
  await page.goto(mail.link!)
  await page.getByRole('button', { name: '确认验证邮箱', exact: true }).click()
  await expect(page.getByRole('main').getByRole('alert')).toContainText('无效或已过期')
})

test('authenticated resend supersedes the previous link without losing the new fragment', async ({ page }) => {
  const email = await registerAccount(page)
  const original = await waitForMail(email, 'verification')
  await loginAccount(page, email)
  await page.goto('/me')
  await page.getByRole('link', { name: '验证邮箱', exact: true }).click()
  await expect(page.getByLabel('邮箱', { exact: true })).toHaveValue(email)
  await page.getByRole('button', { name: '重发验证邮件', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('已受理请求')
  const replacement = await waitForMail(email, 'verification', original.id)
  await page.goto(original.link!)
  await page.getByRole('button', { name: '确认验证邮箱', exact: true }).click()
  await expect(page.getByRole('main').getByRole('alert')).toContainText('无效或已过期')
  await page.goto(replacement.link!)
  await expect(page.getByLabel('验证令牌', { exact: true })).not.toHaveValue('')
  await page.getByRole('button', { name: '确认验证邮箱', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('邮箱验证成功')
  await page.goto('/me')
  await expect(page.getByText('邮箱：已验证', { exact: true })).toBeVisible()
})

test('password recovery replaces credentials, logs out old sessions and does not auto login', async ({ page, context }) => {
  const email = await registerAccount(page)
  await loginAccount(page, email)
  const otherTab = await context.newPage()
  await otherTab.goto('/me')
  await page.goto('/forgot-password')
  await page.getByLabel('邮箱', { exact: true }).fill(email)
  await page.getByRole('button', { name: '请求重置密码', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('已受理请求')
  const mail = await waitForMail(email, 'password_reset')
  await page.goto(mail.link!)
  await expect(page).toHaveURL(/\/reset-password$/)
  await expect(page.getByLabel('重置令牌', { exact: true })).not.toHaveValue('')
  await page.getByLabel('新密码', { exact: true }).fill(recoveredPassword)
  await page.getByLabel('确认新密码', { exact: true }).fill(recoveredPassword)
  await page.getByRole('button', { name: '更新密码并退出旧会话', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  await expect(page.getByRole('status')).toContainText('密码已更新')
  await expect(otherTab).toHaveURL(/\/login/)
  expect((await context.request.get('/api/v1/auth/me')).status()).toBe(401)
  await page.getByLabel('邮箱', { exact: true }).fill(email)
  await page.getByLabel('密码', { exact: true }).fill(browserPassword)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page.getByRole('main').getByRole('alert')).toContainText('邮箱或密码不正确')
  await page.getByLabel('密码', { exact: true }).fill(recoveredPassword)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/\/$/)
  const notification = await waitForMail(email, 'password_changed')
  expect(notification.link).toBeNull()
  await otherTab.close()
})

test('unknown email has the same generic request result and no public Mock mailbox exists', async ({ page, context }) => {
  await page.goto('/forgot-password')
  await page.getByLabel('邮箱', { exact: true }).fill(`unknown-${crypto.randomUUID()}@example.com`)
  await page.getByRole('button', { name: '请求重置密码', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('如果该邮箱符合找回条件')
  expect((await context.request.get('/api/v1/auth/mock-mailbox')).status()).toBe(404)
  expect((await context.request.get('/api/v1/auth/outbox')).status()).toBe(404)
  await mkdir('.verification/p25', { recursive: true })
  await page.screenshot({ path: '.verification/p25/forgot-desktop.png', fullPage: true })
})

test('the dev server cannot serve a private Mock mailbox file', async ({ page, context }) => {
  const email = await registerAccount(page)
  const mail = await waitForMail(email, 'verification')
  const response = await context.request.get('/@fs/' + mail.filePath.replaceAll('\\', '/'))
  expect(response.status()).toBe(403)
  expect((await response.text()).includes('#token=')).toBe(false)
})

